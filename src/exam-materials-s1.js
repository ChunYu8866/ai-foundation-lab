export function placeAnswer(code, n, options, answer, optionExplanations) {
  const target = (n * 3 + Number(code.slice(-2)) + Number(code[3])) % 4;
  const order = [0, 1, 2, 3].filter(i => i !== answer);
  order.splice(target, 0, answer);
  return { options: order.map(i => options[i]), optionExplanations: order.map(i => optionExplanations[i]), answer: target };
}
